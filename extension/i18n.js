// "auto" follows the Chrome UI language; anything other than Korean falls back to English.
function resolveLanguage(setting) {
  if (setting in MESSAGES) return setting;
  return chrome.i18n.getUILanguage().toLowerCase().startsWith("ko") ? "ko" : "en";
}

function translate(language, key, ...args) {
  const message = MESSAGES[language]?.[key] ?? MESSAGES.en[key];
  return typeof message === "function" ? message(...args) : message;
}
